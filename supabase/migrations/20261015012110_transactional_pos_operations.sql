-- Open a shift. The caller supplies a stable shift ID and idempotency key
-- generated by the client, so retries do not open duplicate shifts.
create or replace function public.open_shift(
    p_shift_id uuid,
    p_idempotency_key uuid,
    p_opening_float_cents bigint,
    p_device_id text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user uuid := (select auth.uid());
    v_role public.app_role;
    v_hash text;
    v_existing public.shifts%rowtype;
    v_shift_id uuid;
begin
    if v_user is null then
        raise exception 'Authentication required';
    end if;

    if p_shift_id is null or p_idempotency_key is null then
        raise exception 'Shift ID and idempotency key are required';
    end if;

    if p_opening_float_cents is null or p_opening_float_cents < 0 then
        raise exception 'Opening float must be zero or greater';
    end if;

    select p.role into v_role
    from public.profiles p
    where p.id = v_user and p.active = true;

    if not found or v_role <> 'cashier' then
        raise exception 'Active cashier profile required';
    end if;

    v_hash := md5(
        jsonb_build_object(
            'cashier_id', v_user,
            'opening_float_cents', p_opening_float_cents,
            'device_id', p_device_id
        )::text
    );

    select * into v_existing
    from public.shifts s
    where s.idempotency_key = p_idempotency_key;

    if found then
        if v_existing.request_hash is distinct from v_hash
           or v_existing.cashier_id <> v_user then
            raise exception 'Idempotency key reused with different shift data';
        end if;

        return jsonb_build_object(
            'shift_id', v_existing.id,
            'status', v_existing.status,
            'duplicate', true
        );
    end if;

    insert into public.shifts (
        id, cashier_id, device_id, opening_float_cents,
        status, idempotency_key, request_hash
    )
    values (
        p_shift_id, v_user, p_device_id, p_opening_float_cents,
        'open', p_idempotency_key, v_hash
    )
    on conflict (idempotency_key) do nothing
    returning id into v_shift_id;

    if v_shift_id is null then
        select * into v_existing
        from public.shifts s
        where s.idempotency_key = p_idempotency_key;

        if v_existing.request_hash is distinct from v_hash
           or v_existing.cashier_id <> v_user then
            raise exception 'Idempotency key conflict';
        end if;

        return jsonb_build_object(
            'shift_id', v_existing.id,
            'status', v_existing.status,
            'duplicate', true
        );
    end if;

    return jsonb_build_object(
        'shift_id', v_shift_id,
        'status', 'open',
        'duplicate', false
    );
end;
$$;


-- Close a shift without exposing expected cash or variance to the cashier.
-- Expected cash is calculated by the owner-facing reporting layer.
create or replace function public.close_shift(
    p_shift_id uuid,
    p_counted_cash_cents bigint,
    p_closing_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user uuid := (select auth.uid());
    v_shift public.shifts%rowtype;
begin
    if v_user is null then
        raise exception 'Authentication required';
    end if;

    if p_counted_cash_cents is null or p_counted_cash_cents < 0 then
        raise exception 'Counted cash must be zero or greater';
    end if;

    select * into v_shift
    from public.shifts s
    where s.id = p_shift_id
      and s.cashier_id = v_user
    for update;

    if not found then
        raise exception 'Shift not found for this cashier';
    end if;

    if v_shift.status = 'closed' then
        if v_shift.counted_cash_cents = p_counted_cash_cents
           and v_shift.closing_note is not distinct from p_closing_note then
            return jsonb_build_object(
                'shift_id', v_shift.id,
                'status', 'closed',
                'duplicate', true
            );
        end if;

        raise exception 'Shift is already closed with a different count';
    end if;

    update public.shifts
    set status = 'closed',
        closed_at = now(),
        counted_cash_cents = p_counted_cash_cents,
        closing_note = p_closing_note
    where id = p_shift_id;

    return jsonb_build_object(
        'shift_id', p_shift_id,
        'status', 'closed',
        'duplicate', false
    );
end;
$$;


-- Create a complete cash sale atomically.
-- p_items format:
-- [{"variant_id":"UUID","quantity":2}, ...]
-- Prices are always read from the database, never trusted from the client.
create or replace function public.create_cash_sale(
    p_sale_id uuid,
    p_idempotency_key uuid,
    p_shift_id uuid,
    p_device_id text,
    p_items jsonb,
    p_tendered_cents bigint
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user uuid := (select auth.uid());
    v_role public.app_role;
    v_shift public.shifts%rowtype;
    v_item record;
    v_existing public.sales%rowtype;
    v_sale_id uuid;
    v_item_count integer;
    v_distinct_count integer;
    v_processed integer := 0;
    v_total numeric := 0;
    v_total_cents bigint;
    v_change_cents bigint;
    v_hash text;
begin
    if v_user is null then
        raise exception 'Authentication required';
    end if;

    if p_sale_id is null or p_idempotency_key is null then
        raise exception 'Sale ID and idempotency key are required';
    end if;

    if jsonb_typeof(p_items) <> 'array'
       or jsonb_array_length(p_items) = 0
       or jsonb_array_length(p_items) > 100 then
        raise exception 'Sale must contain between 1 and 100 item lines';
    end if;

    select p.role into v_role
    from public.profiles p
    where p.id = v_user and p.active = true;

    if not found or v_role <> 'cashier' then
        raise exception 'Active cashier profile required';
    end if;

    if p_tendered_cents is null or p_tendered_cents < 0 then
        raise exception 'Cash tendered must be zero or greater';
    end if;

    select count(*), count(distinct x.variant_id)
    into v_item_count, v_distinct_count
    from jsonb_to_recordset(p_items)
        as x(variant_id uuid, quantity integer);

    if v_item_count = 0 or v_item_count <> v_distinct_count then
        raise exception 'Items are empty or contain duplicate variants';
    end if;

    if exists (
        select 1
        from jsonb_to_recordset(p_items)
            as x(variant_id uuid, quantity integer)
        where x.variant_id is null or x.quantity is null or x.quantity <= 0
    ) then
        raise exception 'Each item needs a variant ID and positive quantity';
    end if;

    v_hash := md5(
        jsonb_build_object(
            'shift_id', p_shift_id,
            'items', p_items,
            'payment_method', 'cash',
            'tendered_cents', p_tendered_cents
        )::text
    );

    -- Fast path for retries after a successful server commit.
    select * into v_existing
    from public.sales s
    where s.idempotency_key = p_idempotency_key;

    if found then
        if v_existing.request_hash is distinct from v_hash
           or v_existing.cashier_id <> v_user then
            raise exception 'Idempotency key reused with different sale data';
        end if;

        return jsonb_build_object(
            'sale_id', v_existing.id,
            'status', v_existing.status,
            'total_cents', v_existing.total_cents,
            'duplicate', true
        );
    end if;

    select * into v_shift
    from public.shifts s
    where s.id = p_shift_id
      and s.cashier_id = v_user
      and s.status = 'open'
    for update;

    if not found then
        raise exception 'An open shift for this cashier is required';
    end if;

    -- Recheck after locking the shift: another request may have
    -- committed the same sale while this request was waiting.
    select * into v_existing
    from public.sales s
    where s.idempotency_key = p_idempotency_key;

    if found then
        if v_existing.request_hash is distinct from v_hash
           or v_existing.cashier_id <> v_user then
            raise exception 'Idempotency key reused with different sale data';
        end if;

        return jsonb_build_object(
            'sale_id', v_existing.id,
            'status', v_existing.status,
            'total_cents', v_existing.total_cents,
            'duplicate', true
        );
    end if;

    -- Lock stock rows in stable order to reduce deadlock risk.
    for v_item in
        select x.variant_id, x.quantity,
               v.price_cents, v.stock_on_hand,
               v.active as variant_active,
               p.name as product_name, p.active as product_active,
               v.size, v.colour
        from jsonb_to_recordset(p_items)
            as x(variant_id uuid, quantity integer)
        join public.product_variants v on v.id = x.variant_id
        join public.products p on p.id = v.product_id
        order by v.id
        for update of v
    loop
        v_processed := v_processed + 1;

        if not v_item.variant_active or not v_item.product_active then
            raise exception 'A selected product is inactive';
        end if;

        if v_item.stock_on_hand < v_item.quantity then
            raise exception 'Insufficient stock for variant %',
                v_item.variant_id;
        end if;

        v_total := v_total
            + (v_item.price_cents::numeric * v_item.quantity::numeric);
    end loop;

    if v_processed <> v_item_count then
        raise exception 'One or more selected variants do not exist';
    end if;

    if v_total <= 0 or v_total > 9000000000000000 then
        raise exception 'Sale total is outside the supported range';
    end if;

    v_total_cents := v_total::bigint;

    if p_tendered_cents < v_total_cents then
        raise exception 'Cash tendered is less than the sale total';
    end if;

    v_change_cents := p_tendered_cents - v_total_cents;

    insert into public.sales (
        id, cashier_id, shift_id, device_id, idempotency_key,
        request_hash, status, subtotal_cents, total_cents
    )
    values (
        p_sale_id, v_user, p_shift_id, p_device_id, p_idempotency_key,
        v_hash, 'completed', v_total_cents, v_total_cents
    )
    on conflict (idempotency_key) do nothing
    returning id into v_sale_id;

    if v_sale_id is null then
        select * into v_existing
        from public.sales s
        where s.idempotency_key = p_idempotency_key;

        if v_existing.request_hash is distinct from v_hash
           or v_existing.cashier_id <> v_user then
            raise exception 'Idempotency key conflict';
        end if;

        return jsonb_build_object(
            'sale_id', v_existing.id,
            'status', v_existing.status,
            'total_cents', v_existing.total_cents,
            'duplicate', true
        );
    end if;

    insert into public.sale_items (
        sale_id, variant_id, product_name, variant_description,
        quantity, unit_price_cents, line_total_cents
    )
    select
        v_sale_id,
        x.variant_id,
        p.name,
        concat_ws(' / ', nullif(v.size, ''), nullif(v.colour, '')),
        x.quantity,
        v.price_cents,
        v.price_cents * x.quantity
    from jsonb_to_recordset(p_items)
        as x(variant_id uuid, quantity integer)
    join public.product_variants v on v.id = x.variant_id
    join public.products p on p.id = v.product_id;

    insert into public.payments (
        sale_id, method, amount_cents, tendered_cents, change_cents
    )
    values (
        v_sale_id, 'cash', v_total_cents,
        p_tendered_cents, v_change_cents
    );

    update public.product_variants v
    set stock_on_hand = v.stock_on_hand - x.quantity,
        updated_at = now()
    from jsonb_to_recordset(p_items)
        as x(variant_id uuid, quantity integer)
    where v.id = x.variant_id;

    insert into public.stock_movements (
        variant_id, movement_type, quantity_delta,
        sale_id, note, created_by
    )
    select
        x.variant_id, 'sale', -x.quantity,
        v_sale_id, 'Sale ' || v_sale_id::text, v_user
    from jsonb_to_recordset(p_items)
        as x(variant_id uuid, quantity integer);

    return jsonb_build_object(
        'sale_id', v_sale_id,
        'status', 'completed',
        'total_cents', v_total_cents,
        'change_cents', v_change_cents,
        'duplicate', false
    );
end;
$$;


-- Record a delivery and add its quantities to stock exactly once.
-- The receipt stays pending review; approval does not add stock again.
create or replace function public.submit_stock_receipt(
    p_receipt_id uuid,
    p_idempotency_key uuid,
    p_device_id text,
    p_reference text,
    p_note text,
    p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user uuid := (select auth.uid());
    v_role public.app_role;
    v_existing public.stock_receipts%rowtype;
    v_receipt_id uuid;
    v_item record;
    v_hash text;
    v_count integer;
    v_distinct_count integer;
    v_processed integer := 0;
    v_updated integer := 0;
begin
    if v_user is null then
        raise exception 'Authentication required';
    end if;

    select p.role into v_role
    from public.profiles p
    where p.id = v_user and p.active = true;

    if not found or v_role not in ('cashier', 'owner') then
        raise exception 'Active user profile required';
    end if;

    if p_receipt_id is null or p_idempotency_key is null then
        raise exception 'Receipt ID and idempotency key are required';
    end if;

    if jsonb_typeof(p_items) <> 'array'
       or jsonb_array_length(p_items) = 0
       or jsonb_array_length(p_items) > 100 then
        raise exception 'Receipt must contain between 1 and 100 item lines';
    end if;

    select count(*), count(distinct x.variant_id)
    into v_count, v_distinct_count
    from jsonb_to_recordset(p_items)
        as x(variant_id uuid, quantity integer);

    if v_count = 0 or v_count <> v_distinct_count then
        raise exception 'Receipt items are empty or contain duplicate variants';
    end if;

    if exists (
        select 1
        from jsonb_to_recordset(p_items)
            as x(variant_id uuid, quantity integer)
        where x.variant_id is null or x.quantity is null or x.quantity <= 0
    ) then
        raise exception 'Receipt quantities must be positive';
    end if;

    v_hash := md5(
        jsonb_build_object(
            'reference', p_reference,
            'note', p_note,
            'items', p_items
        )::text
    );

    select * into v_existing
    from public.stock_receipts r
    where r.idempotency_key = p_idempotency_key;

    if found then
        if v_existing.request_hash is distinct from v_hash
           or v_existing.received_by <> v_user then
            raise exception 'Idempotency key reused with different receipt data';
        end if;

        return jsonb_build_object(
            'receipt_id', v_existing.id,
            'status', v_existing.status,
            'duplicate', true
        );
    end if;

    for v_item in
        select x.variant_id, x.quantity,
               v.active as variant_active, p.active as product_active
        from jsonb_to_recordset(p_items)
            as x(variant_id uuid, quantity integer)
        join public.product_variants v on v.id = x.variant_id
        join public.products p on p.id = v.product_id
        order by v.id
        for update of v
    loop
        v_processed := v_processed + 1;

        if not v_item.variant_active or not v_item.product_active then
            raise exception 'Cannot receive an inactive product';
        end if;
    end loop;

    if v_processed <> v_count then
        raise exception 'One or more receipt variants do not exist';
    end if;

    insert into public.stock_receipts (
        id, received_by, device_id, reference, note, status,
        idempotency_key, request_hash
    )
    values (
        p_receipt_id, v_user, p_device_id, p_reference, p_note, 'pending',
        p_idempotency_key, v_hash
    )
    on conflict (idempotency_key) do nothing
    returning id into v_receipt_id;

    if v_receipt_id is null then
        select * into v_existing
        from public.stock_receipts r
        where r.idempotency_key = p_idempotency_key;

        if v_existing.request_hash is distinct from v_hash
           or v_existing.received_by <> v_user then
            raise exception 'Idempotency key conflict';
        end if;

        return jsonb_build_object(
            'receipt_id', v_existing.id,
            'status', v_existing.status,
            'duplicate', true
        );
    end if;

    insert into public.stock_receipt_items (
        receipt_id, variant_id, quantity, note
    )
    select v_receipt_id, x.variant_id, x.quantity, p_note
    from jsonb_to_recordset(p_items)
        as x(variant_id uuid, quantity integer);

    -- Guard against integer overflow of stock_on_hand.
    if exists (
        select 1
        from jsonb_to_recordset(p_items)
            as x(variant_id uuid, quantity integer)
        join public.product_variants v on v.id = x.variant_id
        where v.stock_on_hand > 2147483647 - x.quantity
    ) then
        raise exception 'Stock quantity would exceed the supported limit';
    end if;

    update public.product_variants v
    set stock_on_hand = v.stock_on_hand + x.quantity,
        updated_at = now()
    from jsonb_to_recordset(p_items)
        as x(variant_id uuid, quantity integer)
    where v.id = x.variant_id;

    -- Check every requested variant was updated.
    get diagnostics v_updated = row_count;

    if v_updated <> v_count then
        raise exception 'One or more stock updates failed';
    end if;

    insert into public.stock_movements (
        variant_id, movement_type, quantity_delta,
        receipt_id, note, created_by
    )
    select
        x.variant_id, 'receipt', x.quantity,
        v_receipt_id, 'Pending stock receipt ' || v_receipt_id::text, v_user
    from jsonb_to_recordset(p_items)
        as x(variant_id uuid, quantity integer);

    return jsonb_build_object(
        'receipt_id', v_receipt_id,
        'status', 'pending',
        'duplicate', false
    );
end;
$$;


-- Owner review changes the receipt status only.
-- It deliberately does NOT add stock again.
-- If quantities need correction, record an audited stock adjustment.
create or replace function public.review_stock_receipt(
    p_receipt_id uuid,
    p_approved boolean,
    p_review_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user uuid := (select auth.uid());
    v_receipt public.stock_receipts%rowtype;
    v_new_status text;
begin
    if v_user is null or not (select public.is_owner()) then
        raise exception 'Owner access required';
    end if;

    v_new_status := case when p_approved then 'approved' else 'rejected' end;

    select * into v_receipt
    from public.stock_receipts r
    where r.id = p_receipt_id
    for update;

    if not found then
        raise exception 'Stock receipt not found';
    end if;

    if v_receipt.status <> 'pending' then
        if v_receipt.status = v_new_status then
            return jsonb_build_object(
                'receipt_id', p_receipt_id,
                'status', v_receipt.status,
                'duplicate', true
            );
        end if;

        raise exception 'Receipt has already been reviewed';
    end if;

    update public.stock_receipts
    set status = v_new_status,
        reviewed_by = v_user,
        reviewed_at = now(),
        review_note = p_review_note
    where id = p_receipt_id;

    return jsonb_build_object(
        'receipt_id', p_receipt_id,
        'status', v_new_status,
        'duplicate', false
    );
end;
$$;


-- Record a cash movement on the cashier's own open shift.
create or replace function public.record_cash_movement(
    p_movement_id uuid,
    p_idempotency_key uuid,
    p_shift_id uuid,
    p_movement_type text,
    p_amount_cents bigint,
    p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user uuid := (select auth.uid());
    v_existing public.cash_movements%rowtype;
    v_id uuid;
    v_hash text;
begin
    if v_user is null then
        raise exception 'Authentication required';
    end if;

    if p_movement_id is null or p_idempotency_key is null then
        raise exception 'Movement ID and idempotency key are required';
    end if;

    if p_movement_type not in ('expense', 'cash_drop', 'cash_top_up')
       or p_amount_cents is null or p_amount_cents <= 0
       or length(trim(coalesce(p_reason, ''))) = 0 then
        raise exception 'Valid movement type, positive amount and reason required';
    end if;

    v_hash := md5(
        jsonb_build_object(
            'shift_id', p_shift_id,
            'movement_type', p_movement_type,
            'amount_cents', p_amount_cents,
            'reason', p_reason
        )::text
    );

    select * into v_existing
    from public.cash_movements m
    where m.idempotency_key = p_idempotency_key;

    if found then
        if v_existing.request_hash is distinct from v_hash
           or v_existing.cashier_id <> v_user then
            raise exception 'Idempotency key reused with different movement data';
        end if;

        return jsonb_build_object(
            'movement_id', v_existing.id,
            'duplicate', true
        );
    end if;

    if not exists (
        select 1
        from public.shifts s
        where s.id = p_shift_id
          and s.cashier_id = v_user
          and s.status = 'open'
    ) then
        raise exception 'An open shift for this cashier is required';
    end if;

    insert into public.cash_movements (
        id, shift_id, cashier_id, movement_type, amount_cents,
        reason, idempotency_key, request_hash
    )
    values (
        p_movement_id, p_shift_id, v_user, p_movement_type, p_amount_cents,
        trim(p_reason), p_idempotency_key, v_hash
    )
    on conflict (idempotency_key) do nothing
    returning id into v_id;

    if v_id is null then
        select * into v_existing
        from public.cash_movements m
        where m.idempotency_key = p_idempotency_key;

        if v_existing.request_hash is distinct from v_hash
           or v_existing.cashier_id <> v_user then
            raise exception 'Idempotency key conflict';
        end if;

        return jsonb_build_object(
            'movement_id', v_existing.id,
            'duplicate', true
        );
    end if;

    return jsonb_build_object(
        'movement_id', v_id,
        'duplicate', false
    );
end;
$$;


-- Only authenticated clients may call the cashier-facing operations.
revoke all on function public.open_shift(uuid, uuid, bigint, text)
    from public, anon;
